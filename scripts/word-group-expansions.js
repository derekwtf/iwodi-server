function createClusterLookup() {
  const lookup = {}

  Object.keys(CURATED_CLUSTERS).forEach((categoryKey) => {
    const map = new Map()

    CURATED_CLUSTERS[categoryKey].forEach((cluster) => {
      for (let index = 0; index < cluster.length; index += 1) {
        for (let inner = index + 1; inner < cluster.length; inner += 1) {
          const key = normalizeKey([cluster[index], cluster[inner]])
          if (!map.has(key)) {
            map.set(key, cluster.find((word) => word !== cluster[index] && word !== cluster[inner]))
          }
        }
      }
    })

    lookup[categoryKey] = map
  })

  return lookup
}

const CLUSTER_LOOKUP = createClusterLookup()

function pickFromAdjacency(words, adjacency) {
  const [left, right] = words
  const leftNeighbors = adjacency.get(left) || new Set()
  const rightNeighbors = adjacency.get(right) || new Set()

  const shared = [...leftNeighbors].filter(
    (candidate) => rightNeighbors.has(candidate) && !words.includes(candidate)
  )
  if (shared.length > 0) {
    return shared[0]
  }

  const combined = [...new Set([...leftNeighbors, ...rightNeighbors])].filter(
    (candidate) => !words.includes(candidate)
  )
  return combined[0] || null
}

function pickGenericFallback(categoryKey, words) {
  const [left, right] = words

  if (categoryKey === 'food') {
    if (left.includes('茶') || right.includes('茶')) return '茉莉花茶'
    if (left.includes('奶') || right.includes('奶')) return '酸奶'
    if (left.includes('面') || right.includes('面')) return '米线'
    if (left.includes('鱼') || right.includes('鱼')) return '烤鱼'
    if (left.includes('鸡') || right.includes('鸡')) return '盐酥鸡'
    if (left.includes('包') || right.includes('包')) return '烧卖'
    return '小吃'
  }

  if (categoryKey === 'people') {
    return '同赛道艺人'
  }

  if (categoryKey === 'brands') {
    return '同类品牌'
  }

  if (categoryKey === 'film_tv_variety') {
    return '同类型作品'
  }

  if (categoryKey === 'idioms') {
    return '如出一辙'
  }

  if (categoryKey === 'digital_internet') {
    return '同类设备'
  }

  if (categoryKey === 'daily_items') {
    return '常用物件'
  }

  if (categoryKey === 'city_travel') {
    return '线下场景'
  }

  return null
}

function createPairExpander(source) {
  const adjacencyByCategory = {}

  Object.keys(source)
    .filter((key) => key !== 'meta')
    .forEach((categoryKey) => {
      adjacencyByCategory[categoryKey] = buildAdjacency(source[categoryKey] || [])
    })

  return function expandPairWords(categoryKey, words) {
    const key = normalizeKey(words)
    const clusterMatch = CLUSTER_LOOKUP[categoryKey] ? CLUSTER_LOOKUP[categoryKey].get(key) : null
    if (clusterMatch) {
      return clusterMatch
    }

    const adjacencyMatch = pickFromAdjacency(words, adjacencyByCategory[categoryKey] || new Map())
    if (adjacencyMatch) {
      return adjacencyMatch
    }

    return pickGenericFallback(categoryKey, words)
  }
}

