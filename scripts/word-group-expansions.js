function normalizeKey(words) {
  return [...words].sort((left, right) => left.localeCompare(right, 'zh-Hans-CN')).join('||')
}

function buildAdjacency(pairs) {
  const adjacency = new Map()

  pairs.forEach(({ civilian, spy }) => {
    const left = String(civilian || '').trim()
    const right = String(spy || '').trim()

    if (!left || !right || left === right) {
      return
    }

    if (!adjacency.has(left)) {
      adjacency.set(left, new Set())
    }
    if (!adjacency.has(right)) {
      adjacency.set(right, new Set())
    }

    adjacency.get(left).add(right)
    adjacency.get(right).add(left)
  })

  return adjacency
}

